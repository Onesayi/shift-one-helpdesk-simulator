'use strict';

// Builds the files the app and the design system share. No dependencies.
//
//   node tools/build-design-system.js           write css/tokens.css and design-system/components/bundle.css
//   node tools/build-design-system.js --check   exit 1 if either file is out of date
//
// design-system/tokens.json is the one place colours, shadows, spacing, radii and font stacks are
// defined. css/tokens.css is compiled from it (light on :root, dark under prefers-color-scheme and
// [data-theme="dark"]); the app loads it before css/styles.css. bundle.css is the app's own CSS
// plus a few preview-only helpers, so the design system's component previews match the app.

const fs = require('node:fs');
const path = require('node:path');

const ROOT = path.join(__dirname, '..');
const read = p => fs.readFileSync(path.join(ROOT, p), 'utf8');

function value(v) {
  return /^\{.+\}$/.test(v) ? `var(--${v.slice(1, -1)})` : v;
}

function tokensCss(tokens) {
  const first = tokens.color.themes[0].id, second = tokens.color.themes[1].id;
  const light = [], dark = [];
  for (const t of [...tokens.color.tokens, ...tokens.shadow.tokens]) {
    if (typeof t.value === 'string') { light.push(`  --${t.name}: ${value(t.value)};`); continue; }
    light.push(`  --${t.name}: ${value(t.value[first])};`);
    if (t.value[second] !== undefined) dark.push(`--${t.name}: ${value(t.value[second])};`);
  }
  const other = ['spacing', 'radius', 'layout'].flatMap(f => tokens[f].tokens.map(t => `  --${t.name}: ${t.value};`));
  const fonts = Object.entries(tokens.type.families).map(([k, v]) => `  --font-${k}: ${v};`);
  const darkBlock = dark.map(d => `    ${d}`).join('\n');
  return `/* ${tokens.name} — generated from design-system/tokens.json by tools/build-design-system.js. Don't edit by hand. */
:root {
${light.join('\n')}
${other.join('\n')}
${fonts.join('\n')}
  color-scheme: light;
}
@media (prefers-color-scheme: dark) {
  :root:not([data-theme="light"]) {
${darkBlock}
    color-scheme: dark;
  }
}
:root[data-theme="dark"] {
${dark.map(d => `  ${d}`).join('\n')}
  color-scheme: dark;
}
`;
}

function bundleCss() {
  return `/* Shift One component styles for the design system's previews — generated by tools/build-design-system.js
   from css/styles.css, css/landing.css and css/dispatch.css. Don't edit by hand. */
${read('css/styles.css')}
${read('css/landing.css')}
${read('css/dispatch.css')}
${read('design-system/components/preview-helpers.css')}`;
}

function outputs() {
  const tokens = JSON.parse(read('design-system/tokens.json'));
  return { 'css/tokens.css': tokensCss(tokens), 'design-system/components/bundle.css': bundleCss() };
}

if (require.main === module) {
  const check = process.argv.includes('--check');
  let stale = 0;
  for (const [file, text] of Object.entries(outputs())) {
    const full = path.join(ROOT, file);
    const current = fs.existsSync(full) ? fs.readFileSync(full, 'utf8') : null;
    if (current === text) continue;
    if (check) { console.error(`${file} is out of date. Run: node tools/build-design-system.js`); stale++; }
    else { fs.writeFileSync(full, text); console.log(`wrote ${file}`); }
  }
  process.exit(stale ? 1 : 0);
}

module.exports = { outputs, tokensCss };
